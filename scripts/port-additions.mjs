/** Emits PORT-ADDITIONS.md from the binding declarations in
 *  src/ui/data/bindings.ts. The list is generated, never maintained: a hook
 *  that gains a gap gains a row here on the next run, and
 *  port.bindings.test.ts fails on a hook that declares nothing at all.
 *
 *  Loaded through Vite so the file is read exactly as the application reads
 *  it — same TypeScript, same `@` alias, no second resolver to drift.
 */
import { writeFile } from "node:fs/promises";
import { createServer } from "vite";

const OUT = new URL("../PORT-ADDITIONS.md", import.meta.url);

const server = await createServer({
  configFile: new URL("../vite.config.ts", import.meta.url).pathname,
  server: { middlewareMode: true },
  appType: "custom",
  logLevel: "warn"
});

let bindings;
try {
  ({ BINDINGS: bindings } = await server.ssrLoadModule("/src/ui/data/bindings.ts"));
} finally {
  await server.close();
}

const hooks = Object.keys(bindings).sort();
const withGaps = hooks.filter((hook) => bindings[hook].needed.length > 0);
const clean = hooks.filter((hook) => bindings[hook].needed.length === 0);

const cell = (text) => String(text).replace(/\|/g, "\\|");
const list = (items) => (items.length > 0 ? items.map(cell).join("; ") : "—");

const out = [];
out.push("# Port additions the AI FDE must answer");
out.push("");
out.push(
  "Generated by `npm run port:additions` from the declarations in",
  "`src/ui/data/bindings.ts`. Do not edit this file — edit the binding next to",
  "the fixture it serves and run the script again. §6.7 of",
  "`guidance/AMENDMENT-6-supporting-pages.md` is the shape this keeps and",
  "extends; the register (`guidance/BACKEND-STATE-AND-1B.md`) is where every",
  "verdict below was measured, on 2026-09-04."
);
out.push("");
out.push(
  "Where the front end needs something the ontology does not yet support, the",
  "ontology is what changes. A declared gap is a note for the FDE, never a",
  "reason to redesign the screen."
);
out.push("");
out.push(`${hooks.length} hooks declared · ${withGaps.length} with gaps · ${clean.length} answerable today.`);
out.push("");

out.push("## What each surface needs");
out.push("");
out.push("| for | verdict | needed |");
out.push("| --- | --- | --- |");
for (const hook of withGaps) {
  const b = bindings[hook];
  out.push(`| \`${hook}\` — ${cell(b.serves)} | ${b.status} | ${list(b.needed)} |`);
}
out.push("");

out.push("## Surfaces the backend can answer today");
out.push("");
if (clean.length === 0) {
  out.push("None.");
} else {
  out.push("| for | verdict | reads |");
  out.push("| --- | --- | --- |");
  for (const hook of clean) {
    const b = bindings[hook];
    const reads = [...b.objectTypes, ...b.datasets];
    out.push(`| \`${hook}\` — ${cell(b.serves)} | ${b.status} | ${list(reads)} |`);
  }
}
out.push("");
out.push(
  '"Answerable" means the shape and the act exist and are exercisable — not that',
  "any row exists. 76 of 79 object types hold zero instances, and the only real",
  "data in the build is the corpus."
);
out.push("");

out.push("## Bindings in full");
out.push("");
for (const hook of hooks) {
  const b = bindings[hook];
  out.push(`### \`${hook}\``);
  out.push("");
  out.push(`${b.serves}. Verdict: **${b.status}**. Required by ${list(b.requires)}.`);
  out.push("");
  out.push("| | |");
  out.push("| --- | --- |");
  out.push(`| object types | ${list(b.objectTypes)} |`);
  out.push(`| properties | ${list(b.properties)} |`);
  out.push(`| acts | ${list(b.acts.map((a) => `signature-ready-${a}`))} |`);
  out.push(`| datasets | ${list(b.datasets.map((d) => `signatureReady.${d}`))} |`);
  out.push("");
  if (b.needed.length > 0) {
    out.push("Needed:");
    out.push("");
    for (const item of b.needed) out.push(`- ${item}`);
    out.push("");
  }
  if (b.notes.length > 0) {
    out.push("Rendered rather than hidden:");
    out.push("");
    for (const note of b.notes) out.push(`- ${note}`);
    out.push("");
  }
}

await writeFile(OUT, out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n", "utf8");
process.stdout.write(
  `PORT-ADDITIONS.md — ${hooks.length} hooks, ${withGaps.length} with gaps\n`
);
